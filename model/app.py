from pathlib import Path
import json
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt

from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix,
    ConfusionMatrixDisplay, classification_report
)

BASE_DIR = Path(__file__).resolve().parent
MODEL_DIR = BASE_DIR / "model"
TARGET_COLUMN = "diagnosis"

st.set_page_config(page_title="BITS ML Assignment 2", page_icon="📊", layout="wide")
st.title("Machine Learning Classification Model Evaluation")
st.write("BITS Pilani M.Tech (AIML) – Assignment 2")
st.info("Upload a labelled test CSV containing all 30 input features and the actual diagnosis column. This app loads saved models; it does not retrain them.")

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "knn.joblib",
    "Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "svm.joblib",
}

@st.cache_resource
def load_saved_models():
    loaded = {}
    for name, filename in MODEL_FILES.items():
        path = MODEL_DIR / filename
        if not path.exists():
            raise FileNotFoundError(f"Missing saved model: {path}. Run train_models.py first.")
        loaded[name] = joblib.load(path)
    return loaded

try:
    models = load_saved_models()
except Exception as error:
    st.error(str(error))
    st.stop()

uploaded_file = st.file_uploader("Upload test dataset (CSV)", type=["csv"])
if uploaded_file is None:
    st.caption("For a quick test, use the test_data.csv file generated by train_models.py.")
    if (BASE_DIR / "test_data.csv").exists():
        if st.button("Use the generated test_data.csv"):
            st.session_state["use_default_test"] = True
    if not st.session_state.get("use_default_test", False):
        st.stop()
    test_df = pd.read_csv(BASE_DIR / "test_data.csv")
else:
    test_df = pd.read_csv(uploaded_file)

if TARGET_COLUMN not in test_df.columns:
    st.error(f"The uploaded CSV must contain the target column '{TARGET_COLUMN}' as well as all input features.")
    st.stop()

try:
    with open(MODEL_DIR / "metadata.json", "r") as file:
        metadata = json.load(file)
    feature_columns = metadata["feature_columns"]
except Exception as error:
    st.error(f"Could not read model metadata: {error}")
    st.stop()

missing_columns = [column for column in feature_columns if column not in test_df.columns]
extra_columns = [column for column in test_df.columns if column not in feature_columns + [TARGET_COLUMN]]
if missing_columns:
    st.error(f"Missing required feature columns: {missing_columns}")
    st.stop()
if extra_columns:
    st.warning(f"Extra columns will be ignored: {extra_columns}")

X_test = test_df[feature_columns].apply(pd.to_numeric, errors="coerce")
y_test = test_df[TARGET_COLUMN].astype(str)
if X_test.isnull().any().any():
    st.error("Some feature values are missing or non-numeric. Please correct the CSV and upload again.")
    st.stop()
if y_test.isnull().any():
    st.error("The target column contains missing values.")
    st.stop()

st.subheader("Test dataset overview")
c1, c2, c3 = st.columns(3)
c1.metric("Test instances", len(test_df))
c2.metric("Input features", len(feature_columns))
c3.metric("Target classes", y_test.nunique())
st.dataframe(test_df.head(), use_container_width=True)

selected_model_name = st.selectbox("Select a classification model", list(MODEL_FILES.keys()))
model = models[selected_model_name]

try:
    predictions = model.predict(X_test)
    classes = list(model.classes_)
    if len(classes) == 2:
        if hasattr(model, "predict_proba"):
            score_values = model.predict_proba(X_test)[:, 1]
        else:
            score_values = model.decision_function(X_test)
        auc = roc_auc_score(y_test, score_values)
        precision = precision_score(y_test, predictions, pos_label=classes[1], zero_division=0)
        recall = recall_score(y_test, predictions, pos_label=classes[1], zero_division=0)
        f1 = f1_score(y_test, predictions, pos_label=classes[1], zero_division=0)
    else:
        auc = roc_auc_score(y_test, model.predict_proba(X_test), multi_class="ovr", average="weighted")
        precision = precision_score(y_test, predictions, average="weighted", zero_division=0)
        recall = recall_score(y_test, predictions, average="weighted", zero_division=0)
        f1 = f1_score(y_test, predictions, average="weighted", zero_division=0)

    accuracy = accuracy_score(y_test, predictions)
    mcc = matthews_corrcoef(y_test, predictions)

    st.subheader(f"Evaluation results – {selected_model_name}")
    metric_cols = st.columns(3)
    metric_cols[0].metric("Accuracy", f"{accuracy:.4f}")
    metric_cols[1].metric("AUC Score", f"{auc:.4f}")
    metric_cols[2].metric("Precision", f"{precision:.4f}")
    metric_cols = st.columns(3)
    metric_cols[0].metric("Recall", f"{recall:.4f}")
    metric_cols[1].metric("F1 Score", f"{f1:.4f}")
    metric_cols[2].metric("MCC Score", f"{mcc:.4f}")

    st.subheader("Confusion matrix")
    cm = confusion_matrix(y_test, predictions, labels=classes)
    fig, ax = plt.subplots()
    display = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=classes)
    display.plot(ax=ax, cmap="Blues", colorbar=False)
    st.pyplot(fig)
    plt.close(fig)

    st.subheader("Classification report")
    report = classification_report(y_test, predictions, zero_division=0, output_dict=True)
    st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

    results = pd.DataFrame({"Actual": y_test, "Predicted": predictions})
    st.subheader("Actual vs predicted values")
    st.dataframe(results.head(30), use_container_width=True)
    st.download_button(
        "Download prediction results",
        data=results.to_csv(index=False).encode("utf-8"),
        file_name="predictions.csv",
        mime="text/csv",
    )
except Exception as error:
    st.error(f"Could not evaluate this uploaded dataset: {error}")
    st.caption("Check that the target labels match the labels used during training and that the CSV contains the correct feature columns.")
